"""Run every backend test and write regression_results.md from what actually happened.

    python research/product_specific_conclusions/run_regression.py

Counts per test file, every failure and error with its message, and which files are new in this branch (compared with the
`deployment` branch). The browser tests, the build and the type check are separate commands and are listed at the bottom with
how to run them; their results are recorded by whoever ran them, with the date, not invented here.
"""
from __future__ import annotations

import collections
import datetime
import subprocess
import sys
import time
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "tests"))


class Collect(unittest.TextTestResult):
    def __init__(self, *a, **k):
        super().__init__(*a, **k)
        self.rows: dict[str, collections.Counter] = collections.defaultdict(collections.Counter)

    def module(self, test) -> str:
        return test.__class__.__module__

    def addSuccess(self, test):
        super().addSuccess(test); self.rows[self.module(test)]["passed"] += 1

    def addFailure(self, test, err):
        super().addFailure(test, err); self.rows[self.module(test)]["failed"] += 1

    def addError(self, test, err):
        super().addError(test, err); self.rows[self.module(test)]["errors"] += 1

    def addSkip(self, test, reason):
        super().addSkip(test, reason); self.rows[self.module(test)]["skipped"] += 1


def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True).stdout.strip()


def main() -> None:
    suite = unittest.defaultTestLoader.discover(str(ROOT / "tests"), pattern="test_*.py")
    started = time.time()
    runner = unittest.TextTestRunner(resultclass=Collect, stream=open(Path(sys.argv[0]).with_suffix(".log"), "w", encoding="utf-8"), verbosity=1)
    result = runner.run(suite)
    elapsed = time.time() - started
    new_files = {Path(p).stem for p in git("ls-files", "--others", "--exclude-standard", "tests").split("\n") if p.endswith(".py")}
    new_files |= {Path(p).stem for p in git("diff", "--name-only", "--diff-filter=A", "deployment", "--", "tests").split("\n") if p.endswith(".py")}
    total = collections.Counter()
    md = ["# Regression results", "", f"Generated by `run_regression.py` on {datetime.datetime.now().astimezone().isoformat(timespec='seconds')} · branch `{git('branch', '--show-current')}` · based on `{git('rev-parse', '--short', 'HEAD')}` (the work is uncommitted) · Python {sys.version.split()[0]} · {elapsed:.0f} s.", "",
          "| Test file | Passed | Failed | Errors | Skipped | New in this branch |", "|---|---|---|---|---|---|"]
    for module in sorted(result.rows):
        row = result.rows[module]
        total.update(row)
        md.append(f"| {module} | {row['passed']} | {row['failed']} | {row['errors']} | {row['skipped']} | {'yes' if module in new_files else ''} |")
    new_count = sum(sum(result.rows[m].values()) for m in result.rows if m in new_files)
    all_count = sum(total.values())
    md += ["", f"**{all_count} tests: {total['passed']} passed, {total['failed']} failed, {total['errors']} errors, {total['skipped']} skipped.** {new_count} of them are in test files new in this branch; the other {all_count - new_count} existed before (a few existing files were updated: `test_conclusion.py` for the new wording).", ""]
    problems = [(str(test), trace) for test, trace in result.failures + result.errors]
    if problems:
        md += ["## Failures and errors", ""]
        for name, trace in problems:
            md += [f"### {name}", "", "```", trace[-1500:], "```", ""]
    else:
        md += ["No failures and no errors.", ""]
    md += ["## What the regression tests prove about the saved products", "",
           "- `test_product_conclusion.Regression.test_the_explanation_changes_no_verdict_and_no_decision`: for all 182 saved products, the verdict state, tone, headline, counts, decision, conclusion headline and basis equal the values recorded BEFORE any change (`tests/fixtures/verdict_baseline_before_aspects.json`).",
           "- `test_recommendation_policy`: the decision rules re-stated in `recommendation_policy.py` equal the live ones on every saved product and on a grid of more than 5,000 state and share combinations.",
           "- `test_sync_backend`: a sync against the older production files overwrites nothing and the conclusion generator still runs from the synced folder.",
           "- `test_saved_report_compat`, `test_regression_matrix`, `test_safety_regression`, `test_safety_s5`: the project's existing regression tests for saved reports and hazard rules, unchanged and passing.", "",
           "## Run the rest yourself", "", "```", "npm run build", "npm run check            # 3 `./$types` errors appear in a git worktree with a linked node_modules, also on the unmodified branch; 0 in the main checkout",
           "BASE=http://localhost:8099 node tests/e2e/product-conclusion.mjs   # with `python serve.py --port 8099` running", "```", ""]
    (HERE / "regression_results.md").write_text("\n".join(md), encoding="utf-8")
    print(f"{all_count} tests: {dict(total)}; {len(problems)} problems; written")


if __name__ == "__main__":
    main()
