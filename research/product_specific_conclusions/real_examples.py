"""Genuine before-and-after examples on REAL non-electronics products, with every reason traceable to a source review.

    python research/product_specific_conclusions/real_examples.py

Reads cache/analysed_nongadget.json.gz (made by analyse_real_nongadget.py from the project's own scans, HELD-OUT half only,
analysed by the app's own pipeline). The old text is produced by the real production code (dashboard_utils.py on the `deployment`
branch). The new text is this code. For each product the script prints the decision, the old and new words, and the lines of
"Why this conclusion?" with, for the first quotation of each: the review id, the exact words and their [start, end) in the
review, which it re-checks against the review text before printing.

Writes real_examples.md. Nothing is edited by hand; reviewer names are not in the data and are not printed.
"""
from __future__ import annotations

import gzip
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "backend"))
sys.path.insert(0, str(HERE))

import aspect_profiles as ap  # noqa: E402
import dashboard_utils as new  # noqa: E402
from before_after import load_old  # noqa: E402

PER_PROFILE = {"hair": 2, "skin": 3, "apparel": 2, "appliance": 2, "food": 2}


def find_review(product, review_id):
    for index, review in enumerate(product["comments"]):
        if str(review.get("comment_id") or f"review-{index}") == review_id:
            return review
    return None


def main() -> None:
    path = HERE / "cache" / "analysed_nongadget.json.gz"
    if not path.is_file():
        raise SystemExit("Run analyse_real_nongadget.py first (it analyses real products with the app's pipeline).")
    products = json.load(gzip.open(path, "rt", encoding="utf-8"))
    old = load_old("deployment")
    by_profile: dict[str, list] = {}
    for product in products:
        by_profile.setdefault(ap.profile_key(new.product_category_of(product), new.product_group(product)), []).append(product)
    out = ["# Real before-and-after examples (non-electronics)", "",
           "Generated by `real_examples.py` from REAL reviews in the project's own scans (held-out half), analysed by the app's pipeline. "
           "Old text = the code on `deployment`; new text = this code. Each quotation is re-checked against its review before it is printed. "
           "These are examples, not an evaluation: choosing examples is not measuring.", ""]
    checked = bad = 0
    for profile, want in PER_PROFILE.items():
        out += [f"## {profile}", ""]
        chosen = sorted(by_profile.get(profile, []), key=lambda p: -len(p["comments"]))[:want]
        if not chosen:
            out += ["No real product in the sample.", ""]
        for product in chosen:
            view = new.badge_view(product, aspects=True)
            conclusion = view["conclusion"]
            before = old.badge_view(product)["conclusion"]
            if not conclusion or not before:
                continue
            shares = new._sentiment_shares(product["sentiment_summary"]) or {}
            out += [f"### {product['name'][:90]}", "",
                    f"category `{new.product_category_of(product)}` · decision `{conclusion['decision']}` · verdict `{view['state']}` · {view['reviews_analyzed']} reviews analyzed · "
                    f"positive {round(shares.get('positive', 0) * 100)}% / neutral or unclear {round(shares.get('uncertain', 0) * 100)}% / negative {round(shares.get('negative', 0) * 100)}% · evidence `{conclusion.get('evidence_status')}`", "",
                    "**Before**", "", f"> **{before['lead']}** {before['summary']}", "", "**After**", "", f"> **{conclusion['lead']}** {conclusion.get('body') or conclusion['summary']}", ""]
            for warning in conclusion.get("warnings", []):
                out += [f"> ⚠ {warning}", ""]
            out += [f"*Overall assessment: {conclusion['assessment']}*" + (f" · {conclusion['assessment_note']}" if conclusion.get("assessment_note") else ""), "", "Why this conclusion? (each line with its first quotation and where it comes from)", ""]
            for item in (conclusion.get("evidence") or {}).get("why", [])[:6]:
                q = item["quotes"][0] if item["quotes"] else None
                if not q:
                    continue
                review = find_review(product, q["review_id"])
                raw = str((review or {}).get("content", ""))
                ok = bool(review) and (q["span"] is None or " ".join(raw[q["span"][0]:q["span"][1]].split()).startswith(q["text"].rstrip("…").rstrip()))
                checked += 1
                bad += not ok
                out.append(f"- {item['text']} ({item['kind']}, {item['polarity']}) — review `{q['review_id']}` {q['span']}, {q.get('rating')}★ {q['language']}: “{q['text'][:120]}” {'✔ verified against the review text' if ok else '✘ NOT FOUND'}")
            out.append("")
    out += ["## Verification", "", f"{checked} quotations printed above; {checked - bad} found at their stated position in their review, {bad} not found.", ""]
    (HERE / "real_examples.md").write_text("\n".join(out), encoding="utf-8")
    print(f"wrote real_examples.md ({checked} quotations, {bad} not found)")


if __name__ == "__main__":
    main()
