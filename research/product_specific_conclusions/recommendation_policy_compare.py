"""Compare the live recommendation policy with the experimental candidate on the same saved products.

    python research/product_specific_conclusions/recommendation_policy_compare.py

Writes recommendation_policy_comparison.md (the report, generated: no number in it is typed by hand),
recommendation_policy_comparison.csv (every product) and recommendation_policy_sensitivity.json.

The live policy is reproduced by backend/recommendation_policy.current_decision, which tests/test_recommendation_policy.py
checks against dashboard_utils on every saved product. Nothing here changes a live decision. There are no independent human
conclusion labels yet (research/conclusion_eval sheets are blank), so this compares policies with each other; it cannot say
which one is RIGHT. That needs the annotation.
"""
from __future__ import annotations

import collections
import csv
import gzip
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "backend"))

import dashboard_utils as du  # noqa: E402
import recommendation_policy as rp  # noqa: E402

ORDER = ["recommended", "mixed", "caution", "not_recommended", "not_enough"]
LABEL = {"recommended": "Well reviewed", "mixed": "Mixed reviews", "caution": "Some concerns", "not_recommended": "Not recommended", "not_enough": "Too few reviews"}


def load():
    products = [item["product"] for item in json.load(gzip.open(ROOT / "backend" / "seed" / "saved_products.json.gz", "rt", encoding="utf-8"))]
    rows = []
    for product in products:
        view = du.badge_view(product, aspects=True)
        data = product["sentiment_summary"]
        shares = du._sentiment_shares(data)
        bound = float(data.get("positive_ratio_lower_bound") or 0.0)
        live = (view["conclusion"] or {}).get("decision")
        rows.append({"product": product, "view": view, "shares": shares, "bound": bound, "live": live})
    return rows


def run(rows, neg_dominant=None, opinion_min=None):
    old_nd, old_om = rp.NEG_DOMINANT, rp.OPINION_MIN
    if neg_dominant is not None:
        rp.NEG_DOMINANT = neg_dominant
    if opinion_min is not None:
        rp.OPINION_MIN = opinion_min
    try:
        return [rp.candidate_decision(r["view"]["state"], r["shares"], r["bound"]) for r in rows]
    finally:
        rp.NEG_DOMINANT, rp.OPINION_MIN = old_nd, old_om


def main() -> None:
    rows = load()
    results = run(rows)
    for r in rows:
        assert rp.current_decision(r["view"]["state"], r["shares"], r["bound"]) == r["live"], "the reproduction must match the live decision"
    changed = [(r, new, why) for r, (new, why) in zip(rows, results) if new != r["live"]]
    matrix = collections.Counter((r["live"], new) for r, (new, _) in zip(rows, results))
    n = len(rows)
    sens = {}
    for nd in (0.30, 0.35, 0.40, 0.45):
        for om in (0.20, 0.30, 0.40):
            res = run(rows, nd, om)
            sens[f"NEG_DOMINANT={nd} OPINION_MIN={om}"] = sum(1 for r, (new, _) in zip(rows, res) if new != r["live"])
    (HERE / "recommendation_policy_sensitivity.json").write_text(json.dumps(sens, indent=1), encoding="utf-8")
    with open(HERE / "recommendation_policy_comparison.csv", "w", encoding="utf-8-sig", newline="") as fh:
        writer = csv.writer(fh)
        writer.writerow(["name", "state", "positive_pct", "neutral_pct", "negative_pct", "positive_lower_bound", "live_decision", "candidate_decision", "changed", "rule"])
        for r, (new, why) in zip(rows, results):
            s = r["shares"] or {"positive": 0, "uncertain": 0, "negative": 0}
            writer.writerow([r["product"]["name"][:80], r["view"]["state"], round(s["positive"] * 100), round(s["uncertain"] * 100), round(s["negative"] * 100), round(r["bound"], 2), r["live"], new, "yes" if new != r["live"] else "", why])
    md = ["# Recommendation policy: live versus candidate", "", "Generated by `recommendation_policy_compare.py` on the 182 saved products. **Nothing here changes a live decision.**", "",
          "**What this can and cannot say.** It shows what the candidate would change and why. It cannot say whether the change is *right*: there are no independent human conclusion labels yet (the blind sheets in `research/conclusion_eval/` are unfilled). "
          "Until annotators supply them, the live policy stays and the candidate is experimental.", "",
          "## The two policies", "", "See the docstring of `backend/recommendation_policy.py`. In short: the live policy decides every \"not positive enough\" case from the positive share alone (below 50% is `not_recommended`). "
          "The candidate calls a product `not_recommended` only when negative reviews **dominate** (a majority, or at least 35% and more than the positive share), keeps `caution` for hazard concerns that are not backed by negative dominance, "
          "and calls the rest `mixed`, or `not_enough` when fewer than 30% of reviews took a side. Hazard overrides (`safety_warning`, unreliable reviews, insufficient evidence) are untouched, and the candidate never promotes a product to `recommended`.", "",
          f"## Result on the {n} saved products", "", f"**{len(changed)} of {n} decisions would change** ({len(changed) * 100 // n}%). {n - len(changed)} are identical.", "", "Transition counts (rows: live, columns: candidate):", "",
          "| live \\ candidate | " + " | ".join(ORDER) + " |", "|---|" + "---|" * len(ORDER)]
    for old in ORDER:
        md.append(f"| {old} | " + " | ".join(str(matrix.get((old, new), 0)) or "0" for new in ORDER) + " |")
    md += ["", "## Every changed decision, with its evidence", ""]
    if not changed:
        md.append("None.")
    for r, new, why in sorted(changed, key=lambda t: (t[0]["live"], t[1], t[0]["product"]["name"])):
        s = r["shares"]
        c = r["view"]["conclusion"] or {}
        why_items = (c.get("evidence") or {}).get("why", [])
        top = [w for w in why_items if w["kind"] == "product"][:3]
        md += [f"### {r['product']['name'][:90]}", "",
               f"- `{r['view']['state']}`: positive {round(s['positive'] * 100)}%, neutral or unclear {round(s['uncertain'] * 100)}%, negative {round(s['negative'] * 100)}%, positive lower bound {r['bound']:.2f}, {r['view']['reviews_analyzed']} reviews analyzed.",
               f"- **{r['live']} → {new}** because: {why}.",
               f"- Hazard reports on the card: " + (", ".join(f"{b['category']} {b['mentions']}" for b in r["view"]["badges"] if b["mentions"] and b["category"] in ("safety", "counterfeit", "defect")) or "none") + "."]
        for w in top:
            q = w["quotes"][0]["text"] if w["quotes"] else ""
            md.append(f"- {w['text']} ({w['polarity']}): “{q[:110]}”")
        md.append("")
    scenarios = [
        ("no_warning_signs", (45, 20, 35), 0.40, "the panel's own case: positive exceeds negative"),
        ("no_warning_signs", (25, 65, 10), 0.20, "mostly neutral reviews"),
        ("no_warning_signs", (10, 85, 5), 0.05, "almost nobody took a side"),
        ("no_warning_signs", (30, 25, 45), 0.25, "negative clearly ahead"),
        ("no_warning_signs", (20, 20, 60), 0.15, "negative majority"),
        ("no_warning_signs", (60, 20, 20), 0.50, "positive ahead, not strongly"),
        ("no_warning_signs", (70, 20, 10), 0.62, "positive clearly ahead, lower bound below the 65% needed for `recommended`"),
        ("no_warning_signs", (30, 10, 60), 0.22, "negative majority, little neutral"),
        ("no_warning_signs", (5, 90, 5), 0.02, "high neutral: little product experience"),
        ("no_warning_signs", (90, 5, 5), 0.85, "strongly positive"),
        ("possible_safety_issue", (95, 3, 2), 0.90, "a hazard concern behind praise"),
        ("possible_safety_issue", (30, 60, 10), 0.25, "a hazard concern, mostly neutral"),
        ("possible_counterfeit_or_defect", (43, 17, 40), 0.30, "defect and fake concerns, positive barely ahead"),
        ("possible_counterfeit_or_defect", (45, 20, 35), 0.40, "defect concern, panel's case"),
        ("safety_warning", (95, 3, 2), 0.90, "credible safety reports behind 95% praise"),
    ]
    md += ["## Constructed scenarios (illustrations, not products)", "",
           "\"Evidence\" is the share split the rule reads; \"safety protected\" says whether a hazard warning is still at least as strong as it was (`not_recommended` or `caution` stays one of those; `safety_warning` stays `not_recommended`). "
           "`n/a` means the scenario has no hazard concern.", "",
           "| state | positive / neutral / negative (evidence) | existing | candidate | explanation of the difference | safety protected |", "|---|---|---|---|---|---|"]
    for state, (p, u, ng), bound, note in scenarios:
        data = {"positive": p / 100, "uncertain": u / 100, "negative": ng / 100}
        new, why = rp.candidate_decision(state, data, bound)
        old_decision = rp.current_decision(state, data, bound)
        if state == "no_warning_signs":
            protected = "n/a"
        elif state == "safety_warning":
            protected = "yes" if new == "not_recommended" else "NO"
        else:
            protected = "yes" if new in ("caution", "not_recommended") else "NO"
            if protected == "yes" and old_decision == "not_recommended" and new == "caution":
                protected = "yes, but a WEAKER label (the warning stays on the card)"
        explanation = "no change" if new == old_decision else f"{old_decision} to {new}: {why}"
        md.append(f"| {state} | {p}% / {u}% / {ng}% ({note}) | {old_decision} | {new} | {explanation} | {protected} |")
    md.append("")
    md += ["## Sensitivity: how many decisions change for other thresholds", "", "The two candidate thresholds are round numbers, not tuned. This is how much the answer depends on them (decisions changed, of " + str(n) + "):", "",
           "| NEG_DOMINANT \\ OPINION_MIN | 0.20 | 0.30 | 0.40 |", "|---|---|---|---|"]
    for nd in (0.30, 0.35, 0.40, 0.45):
        md.append(f"| {nd} | " + " | ".join(str(sens[f'NEG_DOMINANT={nd} OPINION_MIN={om}']) for om in (0.20, 0.30, 0.40)) + " |")
    md += ["", "## Recommendation", "",
           "**Do not adopt yet. Keep the live policy; keep the candidate experimental.** Reasons: (1) there is no independent label to say the changed decisions are better; "
           "(2) the thresholds are not validated; (3) one candidate outcome (`not_enough` for mostly-neutral products) needs new card wording because the current label says \"Too few reviews\".", "",
           "If the team wants to proceed: have two annotators judge the changed products blind (`research/conclusion_eval/`), compare each policy's agreement with them, and adopt the candidate only if it agrees better and never hides a hazard. "
           "The hazard-override tests in `tests/test_recommendation_policy.py` would carry over unchanged.", ""]
    (HERE / "recommendation_policy_comparison.md").write_text("\n".join(md), encoding="utf-8")
    print(f"{len(changed)} of {n} would change"); print(dict(matrix)); print(sens)


if __name__ == "__main__":
    main()
